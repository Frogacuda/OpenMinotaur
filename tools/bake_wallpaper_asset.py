#!/usr/bin/env python3
"""Embed supplied PNG pairs unchanged. Baked payloads are embedded during the CMake build."""
from pathlib import Path
from baked_resources import write_payload
root=Path(__file__).resolve().parents[1]
keys=['water-drops','vaporsheep','llama-xp','wooly-sweater']
for index,key in enumerate(keys):
 out=['// Generated by tools/bake_wallpaper_asset.py; original PNG bytes.\n#include "ui_assets.h"\nnamespace mino::ui { namespace {\n']
 for orientation in ['horizontal','vertical']:
  data=(root/f'assets/ui/wallpapers/{key}-{orientation}.png').read_bytes()
  out.append(f'const unsigned char {orientation}[]={{\n')
  include=write_payload(f'platform/wallpaper_{index}.cpp',orientation,data)
  out.append(f'#include \"{include}\"\n')
  out.append('};\n')
 out.append(f'}} Image wallpaper{index}(bool portrait){{return portrait ? Image{{vertical,sizeof vertical}}:Image{{horizontal,sizeof horizontal}};}} }}\n')
 (root/f'platform/wallpaper_{index}.cpp').write_text(''.join(out))
(root/'platform/wallpaper_asset.cpp').write_text('''// Built-in original PNG pairs, split to bound compiler memory.
#include "ui_assets.h"
namespace mino::ui {
Image wallpaper0(bool);Image wallpaper1(bool);Image wallpaper2(bool);Image wallpaper3(bool);
Image wallpaper(int index,bool portrait){
 switch(index){case 1:return wallpaper1(portrait);case 2:return wallpaper2(portrait);case 3:return wallpaper3(portrait);default:return wallpaper0(portrait);}
}
Image defaultWallpaper(bool portrait){return wallpaper(0,portrait);}
}
''')
