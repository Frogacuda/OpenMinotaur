"""Embed collection presentation resources without runtime extraction."""
from pathlib import Path
from baked_resources import write_payload
import io,json,zipfile
root=Path(__file__).resolve().parents[1]
title=root/"modules/live_widgets/assets/title"
document="Minotaur-Title.widgetml"
assets=json.loads((title/document).read_text(encoding="utf-8"))["assets"].values()
files={"title/"+name:title/name for name in [document,*assets]}
files.update({p.relative_to(root/"assets/presentation").as_posix():p for p in (root/"assets/presentation").rglob("*") if p.is_file()})
buffer=io.BytesIO()
with zipfile.ZipFile(buffer,"w",compression=zipfile.ZIP_DEFLATED,compresslevel=9) as archive:
 for name,path in sorted(files.items()):
  entry=zipfile.ZipInfo(name,(2000,1,1,0,0,0));entry.compress_type=zipfile.ZIP_DEFLATED;archive.writestr(entry,path.read_bytes())
data=buffer.getvalue();out=['// Generated by tools/bundle_presentation_assets.py.\n#include "presentation_assets.h"\nnamespace mino {namespace {const unsigned char bytes[]={\n']
include=write_payload('platform/presentation_archive.cpp','bytes',data)
out.append(f'#include \"{include}\"\n')
out.append('};}\nconst unsigned char* presentationArchive(std::size_t& size){size=sizeof bytes;return bytes;}\n}\n')
(root/'platform/presentation_archive.cpp').write_text(''.join(out));print('Embedded',len(files),'presentation resources:',len(data),'bytes')
