#!/usr/bin/env python3
"""Pack unchanged shader sources and LUTs; baked output is embedded by CMake.
Uses deterministic ZIP timestamps and the existing miniz runtime decoder.
"""
from pathlib import Path
from baked_resources import write_payload
import zipfile,io,json
root=Path(__file__).resolve().parents[1];assets=root/'assets/shaders/royale'
data=io.BytesIO()
with zipfile.ZipFile(data,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
    for path in sorted(assets.iterdir()):
        entry=zipfile.ZipInfo(path.name,(2026,1,1,0,0,0));entry.compress_type=zipfile.ZIP_DEFLATED
        z.writestr(entry,path.read_bytes())
raw=data.getvalue()
out=['// Generated by tools/bake_royale_assets.py; source/license in assets/shaders/royale.\n#include "royale_pipeline.h"\nnamespace mino { namespace {\nconst unsigned char data[]={\n']
include=write_payload('platform/royale_assets.cpp','data',raw)
out.append(f'#include \"{include}\"\n')
out.append('};\n}\nconst unsigned char* royaleArchive(std::size_t& size){size=sizeof data;return data;}\n}\n')
(root/'platform/royale_assets.cpp').write_text(''.join(out))
passes=json.loads((assets/'provenance.json').read_text())['passes']
scales={'source':'Source','absolute':'Absolute','viewport':'Viewport'}
out=['// Generated from the supplied preset by tools/bake_royale_assets.py.\n']
for p in passes:
    out.append('{"%s",%s,%s,%s,%s,Scale::%s,Scale::%s,%sf,%sf},\n' % (p['source'],str(p['linear']).lower(),str(p['srgb']).lower(),str(p['floating']).lower(),str(p['mipmap']).lower(),scales[p['xType']],scales[p['yType']],p['xScale'],p['yScale']))
(root/'platform/royale_passes.inl').write_text(''.join(out))
print('Packed CRT Royale source and LUTs:',len(raw),'bytes')

data=io.BytesIO()
with zipfile.ZipFile(data,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
    for path in sorted((root/'assets/shaders/consumer').iterdir()):
        entry=zipfile.ZipInfo(path.name,(2026,1,1,0,0,0));entry.compress_type=zipfile.ZIP_DEFLATED
        z.writestr(entry,path.read_bytes())
raw=data.getvalue()
out=['// Generated by tools/bake_royale_assets.py; source/license in assets/shaders/consumer.\n#include "royale_pipeline.h"\nnamespace mino { namespace {\nconst unsigned char data[]={\n']
include=write_payload('platform/consumer_assets.cpp','data',raw)
out.append(f'#include \"{include}\"\n')
out.append('};\n}\nconst unsigned char* consumerArchive(std::size_t& size){size=sizeof data;return data;}\n}\n')
(root/'platform/consumer_assets.cpp').write_text(''.join(out))
print('Packed CRT Consumer sources:',len(raw),'bytes')
