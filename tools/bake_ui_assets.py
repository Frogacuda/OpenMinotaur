#!/usr/bin/env python3
"""Bake the checked-in UI assets. Optional developer tool; not a build step.
Requires Pillow, NumPy and SciPy. The app itself has no new dependency.
"""
from pathlib import Path
from baked_resources import write_payload
import io
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets' / 'ui'
WIDTH = HEIGHT = 1024
EM, SPREAD, PAD, OVERSAMPLE = 48, 8, 10, 4
IDS = ['minorescue', 'minotron', 'goatup', 'minos', 'gridrunner',
       'fiveaday', 'superoxwars', 'deflex', 'goatup2']


def bake():
    atlas = Image.new('L', (WIDTH, HEIGHT))
    x = y = row_h = 0
    faces = []
    for weight in ['Regular', 'Bold']:
        path = ASSETS / 'fonts' / f'LiberationSans-{weight}.ttf'
        font = ImageFont.truetype(str(path), EM)
        large_font = ImageFont.truetype(str(path), EM * OVERSAMPLE)
        glyphs = []
        for code in range(32, 127):
            char = chr(code)
            left, top, right, bottom = font.getbbox(char, anchor='ls')
            if char == ' ':
                glyphs.append((0, 0, 0, 0, 0, 0, font.getlength(char)))
                continue
            w, h = right - left + 2 * PAD, bottom - top + 2 * PAD
            mask = Image.new('L', (w * OVERSAMPLE, h * OVERSAMPLE))
            ImageDraw.Draw(mask).text(((PAD-left)*OVERSAMPLE, (PAD-top)*OVERSAMPLE),
                                     char, font=large_font, fill=255, anchor='ls')
            inside = np.asarray(mask) >= 128
            signed = (distance_transform_edt(inside) - distance_transform_edt(~inside)) / OVERSAMPLE
            # Average distances, not binary coverage, to preserve smooth contours.
            signed = signed.reshape(h, OVERSAMPLE, w, OVERSAMPLE).mean(axis=(1, 3))
            values = np.clip(np.rint(127.5 + signed * 127.5 / SPREAD), 0, 255).astype(np.uint8)
            if x + w > WIDTH:
                x, y, row_h = 0, y + row_h + 2, 0
            assert y + h <= HEIGHT, 'Font atlas overflow'
            atlas.paste(Image.fromarray(values), (x, y))
            glyphs.append((x, y, w, h, left-PAD, top-PAD, font.getlength(char)))
            x += w + 2
            row_h = max(row_h, h)
        faces.append((glyphs, font.getmetrics()[0]))
    buffer = io.BytesIO()
    atlas.save(buffer, format='PNG', optimize=True)
    out = ['// Generated by tools/bake_ui_assets.py. Payloads live in assets/baked.\n',
           '#include "ui_assets.h"\n#include <cstring>\nnamespace mino::ui {\nnamespace {\n']

    def emit_bytes(name, data):
        out.append(f'const unsigned char {name}[] = {{\n')
        include = write_payload('platform/ui_assets.cpp', name, data)
        out.append(f'#include \"{include}\"\n')
        out.append('};\n')

    emit_bytes('kFontPng', buffer.getvalue())
    for id in IDS:
        emit_bytes('kIcon_' + id, (ASSETS / 'icons' / (id + '.png')).read_bytes())
    for weight, (glyphs, ascent) in zip(['Regular', 'Bold'], faces):
        out.append('const FontFace k' + weight + ' = {{{\n')
        for glyph in glyphs:
            x, y, w, h, ox, oy, advance = glyph
            out.append(f'    {{{x},{y},{w},{h},{ox:.4f}f,{oy:.4f}f,{advance:.4f}f}},\n')
        out.append(f'}}}}, {ascent:.4f}f}};\n')
    out.append('} // namespace\nImage gameIcon(const char* id) {\n')
    for id in IDS:
        out.append(f'    if (std::strcmp(id,"{id}")==0) return {{kIcon_{id},sizeof kIcon_{id}}};\n')
    out.append('    return {nullptr,0};\n}\nImage fontAtlas() { return {kFontPng,sizeof kFontPng}; }\n'
               'const FontFace& fontFace(bool bold) { return bold ? kBold : kRegular; }\n'
               '} // namespace mino::ui\n')
    (ROOT / 'platform' / 'ui_assets.cpp').write_text(''.join(out))
    print(f'Font: {WIDTH}x{HEIGHT} single-channel atlas, {len(buffer.getvalue())} PNG bytes; nine icons embedded.')


if __name__ == '__main__':
    bake()
