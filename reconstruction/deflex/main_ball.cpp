#include "main_ball.h"
#include "neon/integer.h"
#include <cmath>
#include <cassert>
namespace deflex {
void MainGameBall::init(ActorContext &c, uint32_t particleColour, bool demo) {
    flight.init(c.level, demo);
    pos = flight.position;
    vel = flight.velocity;
    size = flight.radius;
    frame = 28;
    age = 0;
    mesh.init(c.random, particleColour, c.level.definition.scalar(0x5fc));
    touchCells = {{{-1, -1}, {-1, -1}, {-1, -1}}};
}
void MainGameBall::run(ActorContext &c, BallFlightContext &movement, BallRecords &records,
                       const std::array<BallTouch, 3> &touches) {
    assert(&movement.voicePlayed == &c.voicePlayed &&
           &movement.pendingParticleLoss == &c.pendingParticleLoss);
    // Source prediction/queue snapshot precedes every completion, damage and
    // touch side effect, including any placements generated by the demo below.
    const auto prediction = flight.predict(c.level.grid, movement.input.pending.has_value());
    age = neon::integers::add32(age, 1);
    if (!movement.demo) {
        if (!c.levelFinished && c.level.targetsRemaining < 1) {
            c.level.grid.fadeLines(1, 4);
            c.levelFinished = true;
            c.levelSucceeded = true;
            mesh.derez(*this, 128, 0, 0.975f, c.random);
            const int sprite = c.level.definition.integer(0xce0), moves = c.level.deflectorsCreated;
            if (sprite == 63 && moves == 3)
                c.services.achievement(6);
            if (sprite == 65 && !c.ravished)
                c.services.achievement(7);
            if (moves == 1)
                c.services.achievement(1);
            if (moves < records.bestMoves()) {
                records.setBestMoves(moves);
                if (c.levelIndex < 4 && records.firstFourInOneMove())
                    c.services.achievement(0);
            }
        } else if (c.levelFinished && c.level.definition.integer(0xce0) == 65 &&
                   c.levelFrames < 1000)
            c.services.achievement(9);
        if (c.pendingParticleLoss > 0)
            mesh.derez(*this, c.pendingParticleLoss, 0, 0.9f, c.random);
        c.pendingParticleLoss = 0;
    }
    if (c.levelFinished)
        return;
    c.ballFraction = float(128 - mesh.depleted) * 0.0078125f;
    if (double(c.ballFraction) < 0.1)
        c.ballFraction = 0.1f;
    if (c.ballFraction < 0)
        c.ballFraction = 0;
    if (mesh.startupFrames != 0) {
        --mesh.startupFrames;
        return;
    }
    static constexpr uint32_t touchColours[] = {0xff00001f, 0x00ff401f, 0x00ffff1f};
    static constexpr float touchSteps[] = {0.01f, -0.01f, 0.02f};
    bool secondaryTouch = false;
    for (size_t i = 0; i < touches.size(); ++i) {
        if (!touches[i].down) {
            touchCells[i] = {-1, -1};
            continue;
        }
        const auto cell = c.level.grid.getCellCoords(touches[i].position);
        auto &displacement = c.level.grid.displacement[i + 1];
        if (std::fabs(displacement.strength) < 1)
            displacement.strength += double(touchSteps[i]);
        if (cell.x != touchCells[i].x || cell.y != touchCells[i].y) {
            touchCells[i] = cell;
            c.level.grid.blendRadius(0.2f, touches[i].position, 0.016666668f, touchColours[i],
                                     0.1f);
            displacement.centre = touches[i].position * 512;
            if (i == 0)
                movement.cuedNote = cell;
            if (i == 2)
                c.reactionFrames = 60;
        }
        if (i == 1)
            secondaryTouch = true;
    }
    if (!movement.demo) {
        if (mesh.lossRate > 0) {
            mesh.lossPhase -= mesh.lossRate;
            if (mesh.lossPhase < 0) {
                mesh.lossPhase += 1;
                mesh.derez(*this, 1, 0.9f, 0.975f, c.random);
            }
        }
    } else if ((c.random.next() & 1023) <= 3) {
        const auto direction = c.random.next();
        if (std::fabs(pos.x) < .34 && std::fabs(pos.y) < .35 && !movement.input.pending)
            movement.input.pending = int((direction & 1) ^ 1);
    }
    c.level.grid.displacement[0] = {pos * 512, 0.3};
    neon::vec3d displaced{pos.x * 512, pos.y * 512, 0};
    c.level.grid.doDisplace(displaced);
    depth = float(displaced.z);
    colour = c.palette[4];
    // Contacts and floor damage share the world's feedback in place. Copying
    // it back after callbacks would overwrite target/hazard contact mutations.
    movement.secondaryTouch = secondaryTouch;
    flight.advance(prediction, movement);
    pos = flight.position;
    vel = flight.velocity;
    size = flight.radius;
}
void MainGameBall::draw(ActorContext &c, ActorRenderer &renderer, neon::vec2d view,
                        uint32_t particleColour, bool paused, bool demo) {
    mesh.draw(*this, c, renderer, view, particleColour, paused, demo);
}
} // namespace deflex
